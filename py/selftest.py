"""用 waterctl 官方单元测试里的全部向量，验证 Python 复刻是否逐字节一致。

运行: python py/selftest.py
"""

from __future__ import annotations

import datetime as dt
import sys

from waterctl_proto import (
    crc16_cgaeaf,
    crc16_changgong,
    dec_as_hex,
    hexdump,
    make_start_epilogue,
    make_start_epilogue_offlinebomb,
    make_unlock_response,
    repair_device_frame,
)

DEVICE = "Water33982"
_fail = 0
_pass = 0


def check(name: str, got, want) -> None:
    global _fail, _pass
    ok = got == want
    if ok:
        _pass += 1
        print(f"  ok   {name}")
    else:
        _fail += 1
        print(f"  FAIL {name}")
        print(f"       got : {got!r}")
        print(f"       want: {want!r}")


def section(title: str) -> None:
    print(f"\n== {title} ==")


def main() -> int:
    section("CRC16 changgong (src/algorithms.spec.ts)")
    for text, want in [
        ("11070", 0xD015),
        ("25333", 0x21E2),
        ("33982", 0x9B39),
        ("45130", 0xE08B),
        ("50312", 0x8D97),
    ]:
        check(f"crc16changgong({text}) == 0x{want:04x}", crc16_changgong(text), want)

    section("CRC8 cgaeaf (src/algorithms.spec.ts)")
    cgaaf_cases = [
        ([0x00, 0x00, 0x05, 0x95, 0x27, 0x03, 0x04, 0x05, 0x06, 0x07, 0x08, 0x09, 0x10, 0x11, 0x12], 0x38),
        ([0x00, 0x9B, 0x05, 0x95, 0x27, 0x03, 0x04, 0x05, 0x06, 0x07, 0x08, 0x09, 0x10, 0x11, 0x12], 0xA2),
        ([0x39, 0x9B, 0x05, 0x95, 0x27, 0x03, 0x04, 0x05, 0x06, 0x07, 0x08, 0x09, 0x10, 0x11, 0x12], 0x5B),
        ([0x00, 0xFF, 0xFF, 0x95, 0x27, 0x03, 0x04, 0x05, 0x06, 0x07, 0x08, 0x09, 0x10, 0x11, 0x12], 0x9F),
        ([0x00, 0x00, 0x01, 0xCF, 0x75, 0x31, 0xD4, 0xFE, 0x87, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00], 0x69),
    ]
    for data, want in cgaaf_cases:
        check(f"crc16cgaeaf({hexdump(data[:5])} ...) == 0x{want:02x}", crc16_cgaeaf(data), want)

    section("BCD")
    for dec, want in [(0, 0x00), (5, 0x05), (42, 0x42), (99, 0x99), (2021, 0x2021)]:
        check(f"decAsHex({dec}) == 0x{want:x}", dec_as_hex(dec), want)

    section("makeUnlockResponse (7 vectors, src/solvers.spec.ts)")
    unlock_cases = [
        (
            [0xFD, 0xFD, 0x09, 0xAE, 0x38, 0x00, 0x00, 0x05, 0x95, 0x27, 0x03, 0x04, 0x05, 0x06, 0x07, 0x08, 0x09, 0x10, 0x11, 0x12],
            [0xFE, 0xFE, 0x09, 0xAF, 0x72, 0x00, 0x00, 0x06, 0xC3, 0x50, 0x9A, 0xC4, 0xFE, 0x87, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00],
        ),
        (
            [0xFD, 0xFD, 0x09, 0xAE, 0xA2, 0x00, 0x9B, 0x05, 0x95, 0x27, 0x03, 0x04, 0x05, 0x06, 0x07, 0x08, 0x09, 0x10, 0x11, 0x12],
            [0xFE, 0xFE, 0x09, 0xAF, 0x44, 0x00, 0x9B, 0x06, 0xF1, 0x30, 0x9A, 0xD3, 0xFE, 0x87, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00],
        ),
        (
            [0xFD, 0xFD, 0x09, 0xAE, 0x5B, 0x39, 0x9B, 0x05, 0x95, 0x27, 0x03, 0x04, 0x05, 0x06, 0x07, 0x08, 0x09, 0x10, 0x11, 0x12],
            [0xFE, 0xFE, 0x09, 0xAF, 0xBD, 0x39, 0x9B, 0x06, 0xF1, 0x30, 0x9A, 0xD3, 0xFE, 0x87, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00],
        ),
        (
            [0xFD, 0xFD, 0x09, 0xAE, 0x9F, 0x00, 0xFF, 0xFF, 0x95, 0x27, 0x03, 0x04, 0x05, 0x06, 0x07, 0x08, 0x09, 0x10, 0x11, 0x12],
            [0xFE, 0xFE, 0x09, 0xAF, 0xD9, 0x00, 0x01, 0x00, 0xD6, 0xAC, 0x3F, 0x3B, 0xFE, 0x87, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00],
        ),
        (
            [0xFD, 0xFD, 0x09, 0xAE, 0xB3, 0x00, 0x34, 0x64, 0x80, 0x14, 0x03, 0x04, 0x05, 0x06, 0x07, 0x08, 0x09, 0x10, 0x11, 0x12],
            [0xFE, 0xFE, 0x09, 0xAF, 0xB1, 0x00, 0x34, 0x65, 0xD6, 0x28, 0x9A, 0xC1, 0xFE, 0x87, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00],
        ),
        (
            [0xFD, 0xFD, 0x09, 0xAE, 0x01, 0x00, 0x81, 0xFF, 0x68, 0x30, 0x03, 0x04, 0x05, 0x06, 0x07, 0x08, 0x09, 0x10, 0x11, 0x12],
            [0xFE, 0xFE, 0x09, 0xAF, 0x68, 0x00, 0x82, 0x00, 0xF1, 0x12, 0xB2, 0x21, 0xFE, 0x87, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00],
        ),
        (
            [0xFD, 0xFD, 0x09, 0xAE, 0xE5, 0x00, 0x01, 0xFF, 0x73, 0x24, 0x03, 0x04, 0x05, 0x06, 0x07, 0x08, 0x09, 0x10, 0x11, 0x12],
            [0xFE, 0xFE, 0x09, 0xAF, 0x4B, 0x00, 0x02, 0x00, 0xCC, 0xCA, 0x9A, 0x20, 0xFE, 0x87, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00],
        ),
    ]
    for i, (req, want) in enumerate(unlock_cases, 1):
        got = make_unlock_response(bytes(req), DEVICE)
        check(f"AE->AF #{i}", hexdump(got), hexdump(want))

    section("B2 startEpilogue (结构 + 固定时间注入)")
    when = bytes([0x21, 0x01, 0x13, 0x12, 0x34, 0x56])  # 2021-01-13 12:34:56
    uid = b"\x12\x34"
    crc = crc16_changgong("33982")

    old = make_start_epilogue(DEVICE, key_auth=False, user_id=uid, when=when)
    check("old fw: 前 5 字节", hexdump(old[:5]), "fe fe 09 b2 01")
    check("old fw: checksum 小端", old[5] | (old[6] << 8), crc)
    check("old fw: mn/保留", hexdump(old[7:9]), "ff 00")
    check("old fw: 用户号", hexdump(old[9:11]), "12 34")
    check("old fw: 时间 BCD", hexdump(old[11:17]), "21 01 13 12 34 56")
    check("old fw: 尾部", hexdump(old[17:20]), "0f 27 00")
    check("old fw: 总长 20", len(old), 20)

    new = make_start_epilogue(DEVICE, key_auth=True, user_id=uid, when=when)
    check("new fw: mn = 0x0b", new[7], 0x0B)
    check("new fw: 与旧固件仅 mn 不同", new[:7] + new[8:], old[:7] + old[8:])

    bomb = make_start_epilogue_offlinebomb(user_id=uid, when=when)
    check("offlinebomb 头", hexdump(bomb[:9]), "fe fe 09 bb 01 01 0d 00 50")
    check("offlinebomb 尾", hexdump(bomb[17:20]), "00 20 00")

    section("收包修补 repair_device_frame")
    body = bytes.fromhex("0909b11d000000")[:0]  # 占位，避免误用
    check("完整帧原样返回", repair_device_frame(bytes.fromhex("fdfd09b11d000000")), bytes.fromhex("fdfd09b11d000000"))
    check("丢 1 字节补 FD", repair_device_frame(bytes.fromhex("fd09b11d000000")), bytes.fromhex("fdfd09b11d000000"))
    check("丢 2 字节补 FD FD", repair_device_frame(bytes.fromhex("09b11d000000")), bytes.fromhex("fdfd09b11d000000"))
    check("单字节残包丢弃", repair_device_frame(bytes.fromhex("fd")), None)
    check("空包丢弃", repair_device_frame(b""), None)

    print(f"\n{_pass} passed, {_fail} failed")
    return 1 if _fail else 0


if __name__ == "__main__":
    sys.exit(main())
